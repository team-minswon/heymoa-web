import { toast } from "@/lib/ui/toast";

/**
 * 같은 id를 쓰면 base-ui가 새 토스트를 쌓지 않고 그 자리를 갱신한다(`lib/ui/toast.ts`).
 * 아래 두 자리가 같은 사건을 각자 알아채므로, 겹쳐도 화면에는 하나만 남아야 한다.
 */
const TOAST_ID = "workspace-gone";

/**
 * 워크스페이스에서 밀려났다는 것을 **한 번만** 알린다.
 *
 * 알아채는 자리가 둘이고, 어느 쪽이 먼저인지는 상황마다 다르다.
 *
 * | 어디 | 언제 |
 * | -- | -- |
 * | `useRedirectWhenWorkspaceGone` | 그 워크스페이스를 **보고 있을 때**. 멤버십 조회가 404 |
 * | `RecordingProvider` | 그 워크스페이스를 **녹음 중일 때**. 세션 조회가 404 — 화면은 다른 곳일 수 있다 |
 *
 * 보면서 녹음까지 하고 있었으면 둘 다 걸린다. 그때 토스트가 둘 뜨면 같은 말을 두 번 하는
 * 셈이라 id로 합친다.
 *
 * **서버 문구(「워크스페이스를 찾을 수 없습니다」)를 쓰지 않는다.** 404는 비멤버에게 존재를
 * 숨기는 수단일 뿐이고, 사용자에게 필요한 것은 **자기가 나가졌다는 사실**이다. 녹음 중이었다면
 * 이 문구가 곧 녹음이 끊긴 이유이기도 하다 — 표시가 말없이 사라지지 않게 하는 것이 목적이다.
 *
 * 공용 표면에는 `success`·`error`뿐이라 `error`를 쓴다. 원치 않은 일이 벌어졌고 사용자가
 * 알아채야 하는 쪽에 가깝다.
 */
export function notifyWorkspaceGone() {
  // **닫을 때까지 남는다.** 숨긴 탭에서도 추방을 감지하는데(세션 폴링이 배경에서도 돈다),
  // 기본 5초로 두면 그 타이머가 사용자가 안 보는 사이에 다 지나가 돌아왔을 때는 녹음과
  // 워크스페이스만 사라져 있다 — 안내를 만든 이유가 통째로 없어진다(codex 병합 리뷰).
  toast.error("이 워크스페이스에서 나가게 되었습니다.", {
    id: TOAST_ID,
    duration: Infinity,
  });
}
